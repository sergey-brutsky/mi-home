using System;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace MiHomeLib.Generators;

[Generator(LanguageNames.CSharp)]
public sealed class MiotPropertyGenerator : IIncrementalGenerator
{
    private const string AttributeName = "MiHomeLib.MiioDevices.Internal.MiotPropertyAttribute";

    private static readonly DiagnosticDescriptor UnsupportedType = new(
        "MIHOME001",
        "Unsupported MIoT property type",
        "MIoT property '{0}' has an unsupported value type",
        "MiHomeLib",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var properties = context.SyntaxProvider.ForAttributeWithMetadataName(
            AttributeName,
            static (node, _) => node is ClassDeclarationSyntax,
            static (attributeContext, _) => GetProperties(attributeContext));

        context.RegisterSourceOutput(properties.Collect(), static (sourceContext, declarations) =>
        {
            foreach (var group in declarations.SelectMany(declaration => declaration)
                         .GroupBy(property => property.TypeName, StringComparer.Ordinal)
                         .OrderBy(group => group.Key, StringComparer.Ordinal))
            {
                var generated = new StringBuilder("// <auto-generated/>\n");
                if (!string.IsNullOrEmpty(group.First().Namespace))
                {
                    generated.Append("namespace ").Append(group.First().Namespace).AppendLine(";").AppendLine();
                }

                generated.Append("partial class ").Append(group.First().ClassName).AppendLine().AppendLine("{");
                foreach (var property in group
                             .GroupBy(property => (property.Name, property.Siid, property.Piid))
                             .Select(properties => properties.First())
                             .OrderBy(property => property.Siid)
                             .ThenBy(property => property.Piid)
                             .ThenBy(property => property.Name, StringComparer.Ordinal))
                {
                    var parseExpression = GetReadExpression(property);
                    if (parseExpression is null)
                    {
                        sourceContext.ReportDiagnostic(Diagnostic.Create(
                            UnsupportedType,
                            property.Location,
                            property.Name));
                        continue;
                    }

                    AppendProperty(generated, property, parseExpression);
                }

                generated.AppendLine("}");
                var hintName = group.First().TypeName
                    .Replace("global::", string.Empty)
                    .Replace('.', '_')
                    .Replace('+', '_') + ".MiotProperties.g.cs";
                sourceContext.AddSource(hintName, generated.ToString());
            }
        });
    }

    private static PropertyInfo[] GetProperties(GeneratorAttributeSyntaxContext context)
    {
        if (context.TargetSymbol is not INamedTypeSymbol type) return [];

        var typeName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var namespaceName = type.ContainingNamespace.IsGlobalNamespace
            ? string.Empty
            : type.ContainingNamespace.ToDisplayString();
        return context.Attributes
            .Where(attribute => attribute.ConstructorArguments.Length == 4)
            .Select(attribute => CreatePropertyInfo(attribute, type, typeName, namespaceName))
            .OfType<PropertyInfo>()
            .ToArray();
    }

    private static PropertyInfo? CreatePropertyInfo(
        AttributeData attribute,
        INamedTypeSymbol type,
        string typeName,
        string namespaceName)
    {
        var arguments = attribute.ConstructorArguments;
        if (arguments[0].Value is not string name ||
            arguments[1].Value is not int siid ||
            arguments[2].Value is not int piid ||
            arguments[3].Value is not ITypeSymbol valueType)
            return null;

        var writable = true;
        ITypeSymbol? wireType = null;
        string? summary = null;
        foreach (var namedArgument in attribute.NamedArguments)
        {
            switch (namedArgument.Key)
            {
                case "Writable" when namedArgument.Value.Value is bool value:
                    writable = value;
                    break;
                case "WireType":
                    wireType = namedArgument.Value.Value as ITypeSymbol;
                    break;
                case "Summary":
                    summary = namedArgument.Value.Value as string;
                    break;
            }
        }

        return new PropertyInfo(
            typeName,
            type.Name,
            namespaceName,
            name,
            siid,
            piid,
            valueType,
            wireType,
            writable,
            summary,
            attribute.ApplicationSyntaxReference?.GetSyntax().GetLocation());
    }

    private static string? GetReadExpression(PropertyInfo property)
    {
        if (property.ValueType.TypeKind == TypeKind.Enum)
        {
            var wireType = property.WireType;
            var parser = wireType is null ? null : GetParser(wireType);
            return parser is null
                ? null
                : $"({property.ValueType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)})await ReadMiotValueAsync({property.Siid}, {property.Piid}, value => {parser}).ConfigureAwait(false)";
        }

        if (property.ValueType.SpecialType == SpecialType.System_String)
            return $"await ReadMiotValueAsync({property.Siid}, {property.Piid}, value => value).ConfigureAwait(false)";

        var valueParser = GetParser(property.ValueType);
        return valueParser is null
            ? null
            : $"await ReadMiotValueAsync({property.Siid}, {property.Piid}, value => {valueParser}).ConfigureAwait(false)";
    }

    private static string? GetParser(ITypeSymbol type)
    {
        string? parser = type.SpecialType switch
        {
            SpecialType.System_Boolean => "bool.Parse(value)",
            SpecialType.System_Byte => "byte.Parse(value, global::System.Globalization.CultureInfo.InvariantCulture)",
            SpecialType.System_UInt16 => "ushort.Parse(value, global::System.Globalization.CultureInfo.InvariantCulture)",
            SpecialType.System_Int16 => "short.Parse(value, global::System.Globalization.CultureInfo.InvariantCulture)",
            SpecialType.System_Int32 => "int.Parse(value, global::System.Globalization.CultureInfo.InvariantCulture)",
            SpecialType.System_UInt32 => "uint.Parse(value, global::System.Globalization.CultureInfo.InvariantCulture)",
            SpecialType.System_Int64 => "long.Parse(value, global::System.Globalization.CultureInfo.InvariantCulture)",
            SpecialType.System_Single => "float.Parse(value, global::System.Globalization.CultureInfo.InvariantCulture)",
            SpecialType.System_Double => "double.Parse(value, global::System.Globalization.CultureInfo.InvariantCulture)",
            _ => null
        };
        return parser;
    }

    private static void AppendProperty(StringBuilder source, PropertyInfo property, string parseExpression)
    {
        var typeName = property.ValueType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var summary = EscapeXml(property.Summary ?? property.Name);
        source.Append("    /// <summary>").Append(summary).AppendLine("</summary>");
        source.Append("    public ").Append(typeName).Append(" Get").Append(property.Name)
            .Append("() => RunSync(Get").Append(property.Name).AppendLine("Async);");
        source.Append("    /// <inheritdoc cref=\"Get").Append(property.Name).AppendLine("\"/>");
        source.Append("    public async global::System.Threading.Tasks.Task<").Append(typeName).Append("> Get")
            .Append(property.Name).Append("Async() => ").Append(parseExpression).AppendLine(";");

        if (!property.Writable) return;

        source.Append("    /// <summary>Sets ").Append(EscapeXml(property.Name)).AppendLine(" on the device.</summary>");
        source.Append("    public void Set").Append(property.Name).Append('(').Append(typeName)
            .Append(" value) => RunSync(() => Set").Append(property.Name).AppendLine("Async(value));");
        source.Append("    /// <inheritdoc cref=\"Set").Append(property.Name).AppendLine("\"/>");
        source.Append("    public async global::System.Threading.Tasks.Task Set").Append(property.Name).Append("Async")
            .Append('(').Append(typeName).AppendLine(" value)");
        source.AppendLine("    {");
        source.Append("        await SetMiotPropertyAsync(").Append(property.Siid).Append(", ").Append(property.Piid)
            .AppendLine(", value).ConfigureAwait(false);");
        source.AppendLine("    }");
    }

    private static string EscapeXml(string value) =>
        value.Replace("\r", " ").Replace("\n", " ")
            .Replace("&", "&amp;")
            .Replace("<", "&lt;")
            .Replace(">", "&gt;");

    private sealed class PropertyInfo
    {
        public PropertyInfo(
            string typeName,
            string className,
            string namespaceName,
            string name,
            int siid,
            int piid,
            ITypeSymbol valueType,
            ITypeSymbol? wireType,
            bool writable,
            string? summary,
            Location? location)
        {
            TypeName = typeName;
            ClassName = className;
            Namespace = namespaceName;
            Name = name;
            Siid = siid;
            Piid = piid;
            ValueType = valueType;
            WireType = wireType;
            Writable = writable;
            Summary = summary;
            Location = location;
        }

        public string TypeName { get; }
        public string ClassName { get; }
        public string Namespace { get; }
        public string Name { get; }
        public int Siid { get; }
        public int Piid { get; }
        public ITypeSymbol ValueType { get; }
        public ITypeSymbol? WireType { get; }
        public bool Writable { get; }
        public string? Summary { get; }
        public Location? Location { get; }
    }
}
