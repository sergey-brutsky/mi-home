using System;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace MiHomeLib.Generators;

[Generator(LanguageNames.CSharp)]
public sealed class ProtocolDeviceCatalogGenerator : IIncrementalGenerator
{
    private const string ModelAttribute = "MiHomeLib.Protocols.ProtocolDeviceModelAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var devices = context.SyntaxProvider.ForAttributeWithMetadataName(
            ModelAttribute,
            static (node, _) => node is TypeDeclarationSyntax,
            static (context, _) => GetDevice(context));

        context.RegisterSourceOutput(devices.Collect(), static (context, devices) =>
        {
            var source = new StringBuilder("""
                // <auto-generated/>
                namespace MiHomeLib.Protocols;

                internal static class ProtocolDeviceCatalog
                {
                    public static readonly global::System.Collections.Generic.IReadOnlyList<ProtocolDeviceEntry> Entries =
                    [

                """);
            // A partial class can carry protocol attributes on more than one declaration.
            foreach (var group in devices.GroupBy(device => device.TypeName, StringComparer.Ordinal)
                         .OrderBy(group => group.Key, StringComparer.Ordinal))
            {
                var type = group.Key;
                source.Append("        new(typeof(").Append(type).Append("), ");
                source.Append(group.Any(device => device.ByModel)
                    ? $"static (id, shortId, loggerFactory) => new {type}(id, shortId, loggerFactory)"
                    : "null");
                source.Append(", ");
                source.Append(group.Any(device => device.ByPdid)
                    ? $"static (id, loggerFactory) => new {type}(id, loggerFactory)"
                    : "null");
                source.AppendLine("),");
            }

            source.AppendLine("    ];").AppendLine("}");
            context.AddSource("ProtocolDeviceCatalog.g.cs", source.ToString());
        });
    }

    private static (string TypeName, bool ByModel, bool ByPdid) GetDevice(GeneratorAttributeSyntaxContext context)
    {
        var typeName = context.TargetSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var byModel = false;
        var byPdid = false;
        foreach (var attribute in context.Attributes)
        {
            if (attribute.ConstructorArguments.IsEmpty) continue;

            var protocol = attribute.ConstructorArguments[0];
            var usesPdid = protocol.Type?.GetMembers().OfType<IFieldSymbol>().Any(field =>
                field.HasConstantValue && (field.Name is "LumiBle" or "LumiMesh") &&
                Equals(field.ConstantValue, protocol.Value)) == true;
            byPdid |= usesPdid;
            byModel |= !usesPdid;
        }

        return (typeName, byModel, byPdid);
    }
}
