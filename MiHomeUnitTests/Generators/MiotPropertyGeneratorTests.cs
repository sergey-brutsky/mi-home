    [Fact]
    public void Generates_Getters_Setters_Enum_Parsing_And_ReadOnly_Property()
    {
        var result = RunGenerator("""
            using System;
            using System.Threading.Tasks;
            using MiHomeLib.MiioDevices.Internal;

            namespace Sample
            {
                public enum Mode { Off, On }
                public abstract class MiotGenericDevice
                {
                    protected T RunSync<T>(Func<Task<T>> action) => default;
                    protected void RunSync(Func<Task> action) { }
                    protected Task<T> ReadMiotValueAsync<T>(int siid, int piid, Func<string, T> parse) => Task.FromResult(default(T));
                    protected Task SetMiotPropertyAsync(int siid, int piid, object value) => Task.CompletedTask;
                }

                [MiotProperty("Enabled", 2, 1, typeof(bool), Summary = "Power state")]
                [MiotProperty("Level", 2, 2, typeof(ushort), Writable = false, Summary = "Current level")]
                [MiotProperty("Mode", 2, 3, typeof(Mode), WireType = typeof(byte), Summary = "Operating mode")]
                public partial class Device : MiotGenericDevice
                {
                    public void Marker() { }
                }
            }

            namespace MiHomeLib.MiioDevices.Internal
            {
                [AttributeUsage(AttributeTargets.Class, AllowMultiple = true)]
                internal sealed class MiotPropertyAttribute(string name, int siid, int piid, Type valueType) : Attribute
                {
                    public bool Writable { get; set; } = true;
                    public Type WireType { get; set; }
                    public string Summary { get; set; }
                }
            }
            """);

        result.Generator.Diagnostics.Should().BeEmpty();
        result.CompilationDiagnostics.Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error)
            .Should().BeEmpty();
        var generated = Normalize(result.Generator.GeneratedSources.Single().SourceText.ToString());
        var expected = Normalize("""
            // <auto-generated/>
            namespace Sample;

            partial class Device
            {
                /// <summary>Power state</summary>
                public bool GetEnabled() => RunSync(GetEnabledAsync);
                /// <inheritdoc cref="GetEnabled"/>
                public async global::System.Threading.Tasks.Task<bool> GetEnabledAsync() => await ReadMiotValueAsync(2, 1, value => bool.Parse(value)).ConfigureAwait(false);
                /// <summary>Sets Enabled on the device.</summary>
                public void SetEnabled(bool value) => RunSync(() => SetEnabledAsync(value));
                /// <inheritdoc cref="SetEnabled"/>
                public async global::System.Threading.Tasks.Task SetEnabledAsync(bool value)
                {
                    await SetMiotPropertyAsync(2, 1, value).ConfigureAwait(false);
                }
                /// <summary>Current level</summary>
                public ushort GetLevel() => RunSync(GetLevelAsync);
                /// <inheritdoc cref="GetLevel"/>
                public async global::System.Threading.Tasks.Task<ushort> GetLevelAsync() => await ReadMiotValueAsync(2, 2, value => ushort.Parse(value, global::System.Globalization.CultureInfo.InvariantCulture)).ConfigureAwait(false);
                /// <summary>Operating mode</summary>
                public global::Sample.Mode GetMode() => RunSync(GetModeAsync);
                /// <inheritdoc cref="GetMode"/>
                public async global::System.Threading.Tasks.Task<global::Sample.Mode> GetModeAsync() => (global::Sample.Mode)await ReadMiotValueAsync(2, 3, value => byte.Parse(value, global::System.Globalization.CultureInfo.InvariantCulture)).ConfigureAwait(false);
                /// <summary>Sets Mode on the device.</summary>
                public void SetMode(global::Sample.Mode value) => RunSync(() => SetModeAsync(value));
                /// <inheritdoc cref="SetMode"/>
                public async global::System.Threading.Tasks.Task SetModeAsync(global::Sample.Mode value)
                {
                    await SetMiotPropertyAsync(2, 3, value).ConfigureAwait(false);
                }
            }
            """);
        generated.Should().Be(expected);
    }

    [Fact]
    public void Reports_Mihome001_For_Unsupported_Value_Type()
    {
        var result = RunGenerator("""
            using System;
            using System.Threading.Tasks;
            using MiHomeLib.MiioDevices.Internal;

            namespace Sample
            {
                public abstract class MiotGenericDevice
                {
                    protected T RunSync<T>(Func<Task<T>> action) => default;
                    protected void RunSync(Func<Task> action) { }
                    protected Task<T> ReadMiotValueAsync<T>(int siid, int piid, Func<string, T> parse) => Task.FromResult(default(T));
                    protected Task SetMiotPropertyAsync(int siid, int piid, object value) => Task.CompletedTask;
                }

                [MiotProperty("Unsupported", 1, 1, typeof(DateTime))]
                public partial class Device : MiotGenericDevice
                {
                    public void Marker() { }
                }
            }

            namespace MiHomeLib.MiioDevices.Internal
            {
                [AttributeUsage(AttributeTargets.Class, AllowMultiple = true)]
                internal sealed class MiotPropertyAttribute(string name, int siid, int piid, Type valueType) : Attribute
                {
                    public bool Writable { get; set; } = true;
                    public Type WireType { get; set; }
                    public string Summary { get; set; }
                }
            }
            """);

        result.Generator.Diagnostics.Should().ContainSingle()
            .Which.Id.Should().Be("MIHOME001");
        result.Generator.Diagnostics.Single().GetMessage().Should().Contain("Unsupported");
    }

    private static (GeneratorRunResult Generator, ImmutableArray<Diagnostic> CompilationDiagnostics) RunGenerator(string source)
    {
        var syntaxTree = CSharpSyntaxTree.ParseText(source);
        var references = ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!)
            .Split(Path.PathSeparator)
            .Select(path => MetadataReference.CreateFromFile(path));
        var compilation = CSharpCompilation.Create(
            "GeneratorTests",
            [syntaxTree],
            references,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
        GeneratorDriver driver = CSharpGeneratorDriver.Create(new MiotPropertyGenerator().AsSourceGenerator());
        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out var outputCompilation, out _);
        return (driver.GetRunResult().Results.Single(), outputCompilation.GetDiagnostics().ToImmutableArray());
    }

    private static string Normalize(string source) =>
        CSharpSyntaxTree.ParseText(source).GetRoot().NormalizeWhitespace().ToFullString();
}
